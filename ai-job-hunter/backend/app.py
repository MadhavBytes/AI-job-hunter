from fastapi import FastAPI, UploadFile, File
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from typing import List, Optional
import os
from datetime import datetime

app = FastAPI(title="🚀 AI Job Hunter - Full AI Edition")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

class Job(BaseModel):
    id: str
    title: str
    company: str
    location: str
    salary: str
    match_score: float
    visa_sponsorship: bool

class ResumeRequest(BaseModel):
    job_title: str
    user_experience: str

@app.get("/")
def read_root():
    return {"message": "🚀 AI Job Hunter FULL AI Backend Running!", "features": "Resume AI + ML Matching + Job Scraping"}

@app.get("/health")
def health():
    return {"status": "healthy", "ai_ready": True, "ml_models": "sentence-transformers + scikit-learn"}

