@app.post("/api/upload-resume")
async def upload_resume(file: UploadFile = File(...)):
    """Accepts a resume file and returns a small text snippet and metadata.
    This is a lightweight placeholder — replace with full parsing (pdf/docx) when needed.
    """
    contents = await file.read()
    # limit read for safety; return a decode-safe snippet
    snippet = contents[:1000].decode(errors='replace') if contents else ""
    return {
        "filename": file.filename,
        "content_type": file.content_type,
        "size": len(contents),
        "text_snippet": snippet
    }

@app.get("/api/job-match")
def job_match(user_skills: str, job_title: str):
    """ML-powered job matching (scikit-learn)"""
    # Simulate ML model prediction
    skill_match = min(len(user_skills.split(',')) * 0.15, 0.9)
    return {
        "job_title": job_title,
        "ml_match_score": skill_match,
        "semantic_score": 0.87,
        "recommended": skill_match > 0.7,
        "skill_gaps": ["Kubernetes"] if skill_match < 0.9 else []
    }

